#!/usr/bin/env node
// Regenerates tests/pending/*.pending.spec.ts from the two source xlsx test
// case files, for every "Auto: Y" case that isn't yet hand-implemented
// (tracked in scripts/implemented-cases.json).
//
// Run after the source Excel files change, or after moving a case from
// pending to a real spec file (update implemented-cases.json first).
//
//   node scripts/generate-pending-tests.js
//
// Each generated test uses `test.fixme(...)`, so it shows up in
// `npx playwright test --list` and in reports, but never executes — safe to
// commit and safe to run in CI alongside real tests.
const fs = require('fs');
const path = require('path');
const { extractAllCases } = require('./lib/extract-cases');

const ROOT = path.join(__dirname, '..');
const PENDING_DIR = path.join(ROOT, 'tests', 'pending');
const IMPLEMENTED_FILE = path.join(__dirname, 'implemented-cases.json');

function escapeForTsString(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function slugModule(moduleCode) {
  return moduleCode.toLowerCase().replace(/[^a-z0-9-]/g, '');
}

function renderCaseComment(c) {
  const lines = [
    `Test Case: ${c.tcId} [${c.priority}]`,
    `${c.tcDesc}`,
    '',
    'Script:',
    ...c.script.split(/\r?\n/).map((l) => `  ${l}`),
    '',
    'Expected Result:',
    ...c.expected.split(/\r?\n/).map((l) => `  ${l}`),
  ];
  if (c.remarks) {
    lines.push('', `Remarks: ${c.remarks.replace(/\r?\n/g, ' | ')}`);
  }
  return lines.map((l) => ` * ${l}`.trimEnd()).join('\n');
}

function renderModuleFile(moduleCode, moduleTitle, modulePath, casesByScenario) {
  const header = `/**
 * PENDING — generated by scripts/generate-pending-tests.js. Do not hand-edit;
 * re-run the script after updating scripts/implemented-cases.json instead.
 *
 * Module: ${moduleCode} — ${moduleTitle}
 * Path(s): ${modulePath}
 *
 * Every case below is "Auto: Y" in the source test-case sheet but not yet
 * implemented. test.fixme() lists them in reports without executing them.
 *
 * To implement one:
 *   1. Move/copy it into a real spec file (see tests/auth or
 *      tests/admin/user-management for the pattern: Page Objects from
 *      src/pages, fixtures from src/fixtures/pages.fixtures).
 *   2. Add its Test Case ID to scripts/implemented-cases.json.
 *   3. Re-run: node scripts/generate-pending-tests.js
 */
import { test } from '@playwright/test';
`;

  const blocks = [];
  for (const [scenarioKey, cases] of casesByScenario) {
    const describeBody = cases
      .map((c) => {
        const title = escapeForTsString(`${c.tcId} [${c.priority}] ${c.tcDesc}`);
        return `  /**\n${renderCaseComment(c)}\n   */\n  test.fixme(\`${title}\`, async ({ page }) => {\n    // TODO: implement — see the doc comment above for Script / Expected Result.\n  });`;
      })
      .join('\n\n');
    const describeTitle = escapeForTsString(scenarioKey);
    blocks.push(`test.describe(\`${describeTitle}\`, () => {\n${describeBody}\n});`);
  }

  return `${header}\n${blocks.join('\n\n')}\n`;
}

function main() {
  const implemented = new Set(JSON.parse(fs.readFileSync(IMPLEMENTED_FILE, 'utf-8')));
  const all = extractAllCases(ROOT);
  const pending = all.filter((c) => c.autoFlag === 'Y' && !c.retired && !c.deferred && !implemented.has(c.tcId));

  const byModule = new Map();
  for (const c of pending) {
    if (!byModule.has(c.moduleCode)) byModule.set(c.moduleCode, []);
    byModule.get(c.moduleCode).push(c);
  }

  fs.mkdirSync(PENDING_DIR, { recursive: true });

  const writtenFiles = new Set();
  for (const [moduleCode, cases] of byModule) {
    const byScenario = new Map();
    for (const c of cases) {
      const key = `${c.scenarioId} ${c.scenarioDesc}`.trim();
      if (!byScenario.has(key)) byScenario.set(key, []);
      byScenario.get(key).push(c);
    }

    const fileName = `${slugModule(moduleCode)}.pending.spec.ts`;
    const filePath = path.join(PENDING_DIR, fileName);
    const content = renderModuleFile(moduleCode, cases[0].moduleTitle, cases[0].modulePath, byScenario);
    fs.writeFileSync(filePath, content, 'utf-8');
    writtenFiles.add(fileName);
    console.log(`  wrote ${path.relative(ROOT, filePath)} (${cases.length} pending cases)`);
  }

  // Remove stale pending files for modules that are now fully implemented.
  if (fs.existsSync(PENDING_DIR)) {
    for (const existing of fs.readdirSync(PENDING_DIR)) {
      if (existing.endsWith('.pending.spec.ts') && !writtenFiles.has(existing)) {
        fs.unlinkSync(path.join(PENDING_DIR, existing));
        console.log(`  removed stale ${path.join('tests/pending', existing)}`);
      }
    }
  }

  console.log(`\nTotal Auto:Y cases: ${all.filter((c) => c.autoFlag === 'Y').length}`);
  console.log(`Implemented: ${implemented.size}`);
  console.log(`Pending (generated): ${pending.length}`);
  console.log(`Modules with pending cases: ${byModule.size}`);
}

main();
